ALTER TABLE live_auctions ADD COLUMN IF NOT EXISTS catalog_revision bigint NOT NULL DEFAULT 0;
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS enabled boolean NOT NULL DEFAULT true;

CREATE TABLE auth_sessions (
    id varchar(64) PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    expires_at timestamp with time zone NOT NULL,
    revoked boolean NOT NULL DEFAULT false
);
CREATE INDEX auth_sessions_user_idx ON auth_sessions(user_id);
CREATE INDEX auth_sessions_expiration_idx ON auth_sessions(expires_at);

CREATE TABLE login_attempts (
    key varchar(64) PRIMARY KEY,
    window_start timestamp with time zone NOT NULL,
    attempts integer NOT NULL
);

CREATE TABLE auction_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city varchar(255) NOT NULL,
    revision bigint NOT NULL,
    payload text NOT NULL,
    created_at timestamp with time zone NOT NULL,
    UNIQUE(city, revision)
);
CREATE INDEX auction_events_age_idx ON auction_events(created_at);
CREATE INDEX bid_logs_round_idx ON bid_logs(player_id, auction_round, id DESC);
CREATE INDEX players_city_status_idx ON players(lower(location), status);
CREATE INDEX players_updated_idx ON players(lower(location), updated_at);
CREATE INDEX teams_city_idx ON teams(lower(location));
