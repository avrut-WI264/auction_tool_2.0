-- Baseline for fresh installations. Existing installations must explicitly baseline at version 0.

CREATE TABLE IF NOT EXISTS teams (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location character varying(255) NOT NULL,
    logo_svg text,
    logo_url text,
    owner_name character varying(255) NOT NULL,
    purse_remaining integer NOT NULL,
    team_name character varying(255) NOT NULL,
    theme_color character varying(255),
    updated_at timestamp(6) without time zone,
    UNIQUE (team_name, location)
);

CREATE TABLE IF NOT EXISTS app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city character varying(255) NOT NULL,
    password character varying(255) NOT NULL,
    role character varying(255) NOT NULL,
    username character varying(255) NOT NULL,
    team_id bigint,
    UNIQUE (username), FOREIGN KEY (team_id) REFERENCES teams(id)
);

CREATE TABLE IF NOT EXISTS players (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_price integer NOT NULL,
    email character varying(255) NOT NULL,
    full_name character varying(255) NOT NULL,
    gender character varying(255) NOT NULL,
    image_url text,
    location character varying(255) NOT NULL,
    mobile_number character varying(255),
    skill_level character varying(255) NOT NULL,
    sold_price integer,
    status character varying(255) NOT NULL,
    updated_at timestamp(6) without time zone,
    wissen_id character varying(255) NOT NULL,
    years_of_experience character varying(255),
    sold_team_id bigint,
    CONSTRAINT players_gender_check CHECK (((gender)::text = ANY ((ARRAY['Male'::character varying, 'Female'::character varying])::text[]))),
    CONSTRAINT players_skill_level_check CHECK (((skill_level)::text = ANY ((ARRAY['Beginner'::character varying, 'Intermediate'::character varying, 'Advanced'::character varying])::text[]))),
    CONSTRAINT players_status_check CHECK (((status)::text = ANY ((ARRAY['UNSOLD'::character varying, 'SOLD'::character varying, 'PASSED'::character varying])::text[]))),
    UNIQUE (wissen_id, location), FOREIGN KEY (sold_team_id) REFERENCES teams(id)
);

CREATE TABLE IF NOT EXISTS player_stats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matches_lost integer,
    matches_played integer,
    matches_won integer,
    wissen_id character varying(255),
    player_id bigint,
    UNIQUE (player_id), FOREIGN KEY (player_id) REFERENCES players(id)
);

CREATE TABLE IF NOT EXISTS bid_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_round character varying(255),
    bid_amount integer NOT NULL,
    created_at timestamp(6) without time zone,
    location character varying(255) NOT NULL,
    team_id bigint,
    team_name character varying(255) NOT NULL,
    player_id bigint NOT NULL,
    FOREIGN KEY (player_id) REFERENCES players(id)
);

CREATE TABLE IF NOT EXISTS live_auctions (
    city character varying(255) PRIMARY KEY,
    active_player_id bigint,
    auction_round character varying(255),
    current_bid integer,
    gender character varying(255),
    highest_bidder_team character varying(255),
    highest_bidder_team_id bigint,
    revision bigint NOT NULL,
    skill_level character varying(255),
    started boolean NOT NULL
);
